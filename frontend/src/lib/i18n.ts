export type TranslationKey = keyof typeof translations.en;

export const getLang = (): Language => {
  if (typeof window !== "undefined") {
    return (localStorage.getItem('edu_lang') as Language) || 'en';
  }
  return 'en';
};

export const setLang = (lang: Language) => {
  if (typeof window !== "undefined") {
    localStorage.setItem('edu_lang', lang);
    window.location.reload();
  }
};

export const t = (key: keyof typeof translations.en): string => {
  const lang = getLang();
  return translations[lang][key] || translations.en[key];
};

/**
 * Custom hook to handle translations safely in Next.js (avoiding hydration mismatch).
 * It returns the translation function and current language once the component has mounted.
 */
export function useTranslation() {
  const [mounted, setMounted] = useState(false);
  useEffect(() => {
    setMounted(true);
  }, []);

  const translate = (key: keyof typeof translations.en): string => {
    if (!mounted) return translations.en[key]; // Always render English on first client pass to match Server
    return t(key);
  };

  return {
    t: translate,
    lang: mounted ? getLang() : 'en',
    isAr: mounted ? getLang() === 'ar' : false,
    mounted
  };
}
